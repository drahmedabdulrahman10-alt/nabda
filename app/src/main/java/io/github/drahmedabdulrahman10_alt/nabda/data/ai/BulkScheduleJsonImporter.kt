package io.github.drahmedabdulrahman10_alt.nabda.data.ai

import io.github.drahmedabdulrahman10_alt.nabda.data.model.TaskPriority
import io.github.drahmedabdulrahman10_alt.nabda.util.ArabicCalendarUtils
import java.util.Date
import org.json.JSONArray
import org.json.JSONObject

data class ScheduledDayDto(
    val dateIso: String,
    val date: Date,
    val tasks: List<ParsedTaskDto>
)

data class ScheduleImportSummary(
    val weeksProcessed: Int,
    val daysProcessed: Int,
    val tasksCreated: Int,
    val firstImportedDayId: String?
)

/**
 * Parses bulk multi-day JSON schedules generated by external AI chatbots (Gemini, ChatGPT, Claude)
 * and provides a one-click AI Prompt Generator tailored for the "نَبضة" (Nabda) JSON schema.
 */
object BulkScheduleJsonImporter {

    /**
     * Parses a JSON string adhering to:
     * ```json
     * {
     *   "schedule": [
     *     {
     *       "date": "2026-11-02",
     *       "tasks": [
     *         { "title": "مذاكرة محاضرة الباطنة الأولى", "priority": "HIGH" }
     *       ]
     *     }
     *   ]
     * }
     * ```
     */
    fun parseScheduleJson(rawInput: String): Result<List<ScheduledDayDto>> {
        val trimmed = rawInput.trim()
        if (trimmed.isEmpty()) {
            return Result.failure(
                IllegalArgumentException("الرجاء لصق كود الـ JSON الخاص بالجدول أولاً.")
            )
        }

        val cleaned = stripMarkdownFences(trimmed)

        return try {
            val scheduleArray: JSONArray = when {
                cleaned.startsWith("{") -> {
                    val rootObj = JSONObject(cleaned)
                    rootObj.optJSONArray("schedule")
                        ?: rootObj.optJSONArray("days")
                        ?: return Result.failure(
                            IllegalArgumentException("لم يتم العثور على مصفوفة \"schedule\" داخل كود JSON.")
                        )
                }
                cleaned.startsWith("[") -> {
                    JSONArray(cleaned)
                }
                else -> {
                    return Result.failure(
                        IllegalArgumentException("صيغة JSON غير صالحة. تأكد من نسخ الكود الذي يبدأ بـ { وينتهي بـ }.")
                    )
                }
            }

            if (scheduleArray.length() == 0) {
                return Result.failure(
                    IllegalArgumentException("قائمة \"schedule\" فارغة ولا تحتوي على أي أيام.")
                )
            }

            // Group tasks by normalized date so duplicate dates in the JSON are merged cleanly
            val tasksByDate = linkedMapOf<String, Pair<Date, MutableList<ParsedTaskDto>>>()

            for (i in 0 until scheduleArray.length()) {
                val dayObj = scheduleArray.optJSONObject(i) ?: continue
                val rawDateStr = dayObj.optString("date", "").trim()
                if (rawDateStr.isEmpty()) {
                    return Result.failure(
                        IllegalArgumentException("أحد الأيام في الجدول يفتقد حقل التاريخ \"date\" (مثال: \"2026-11-02\").")
                    )
                }

                val parsedDate = ArabicCalendarUtils.parseFlexibleDate(rawDateStr)
                    ?: return Result.failure(
                        IllegalArgumentException("صيغة التاريخ \"$rawDateStr\" غير صالحة. استخدم الصيغة YYYY-MM-DD مثل 2026-11-02.")
                    )

                val normalizedIso = ArabicCalendarUtils.formatIsoDate(parsedDate)
                val tasksArray = dayObj.optJSONArray("tasks") ?: JSONArray()
                val dayTasks = mutableListOf<ParsedTaskDto>()

                for (j in 0 until tasksArray.length()) {
                    val taskObj = tasksArray.optJSONObject(j) ?: continue
                    val title = taskObj.optString("title", "").trim()
                    val priorityRaw = taskObj.optString("priority", "MEDIUM").trim()
                    if (title.isNotBlank()) {
                        dayTasks.add(
                            ParsedTaskDto(
                                title = title.take(300),
                                priority = parseFlexiblePriority(priorityRaw)
                            )
                        )
                    }
                }

                if (dayTasks.isNotEmpty()) {
                    val existing = tasksByDate[normalizedIso]
                    if (existing != null) {
                        existing.second.addAll(dayTasks)
                    } else {
                        tasksByDate[normalizedIso] = parsedDate to dayTasks
                    }
                }
            }

            val resultList = tasksByDate.map { (iso, pair) ->
                ScheduledDayDto(
                    dateIso = iso,
                    date = pair.first,
                    tasks = pair.second
                )
            }.sortedBy { it.date.time }

            if (resultList.isEmpty()) {
                Result.failure(
                    IllegalArgumentException("لم يتم العثور على أي مهام صالحة داخل الأيام المحددة في JSON.")
                )
            } else {
                Result.success(resultList)
            }
        } catch (e: Exception) {
            Result.failure(
                IllegalArgumentException(
                    "تعذّر قراءة كود JSON: تأكد من صحة الأقواس والفواصل (${e.localizedMessage ?: "خطأ في الصيغة"})."
                )
            )
        }
    }

    private fun parseFlexiblePriority(raw: String): TaskPriority {
        return when (raw.trim().uppercase()) {
            "HIGH", "مرتفعة", "عالية", "ضروري", "عاجل", "1" -> TaskPriority.HIGH
            "LOW", "منخفضة", "عادي", "بسيطة", "3" -> TaskPriority.LOW
            "MEDIUM", "متوسطة", "متوسط", "2" -> TaskPriority.MEDIUM
            else -> TaskPriority.fromString(raw)
        }
    }

    /**
     * Strips markdown code blocks (` ```json ... ``` `) and extracts the outermost JSON object or array.
     */
    internal fun stripMarkdownFences(rawText: String): String {
        var cleaned = rawText
            .replace(Regex("```json", RegexOption.IGNORE_CASE), "")
            .replace("```", "")
            .trim()

        val firstBrace = cleaned.indexOf('{')
        val lastBrace = cleaned.lastIndexOf('}')
        val firstBracket = cleaned.indexOf('[')
        val lastBracket = cleaned.lastIndexOf(']')

        if (firstBrace != -1 && lastBrace != -1 && lastBrace > firstBrace) {
            if (firstBracket == -1 || firstBrace < firstBracket) {
                cleaned = cleaned.substring(firstBrace, lastBrace + 1)
                return cleaned.trim()
            }
        }
        if (firstBracket != -1 && lastBracket != -1 && lastBracket > firstBracket) {
            cleaned = cleaned.substring(firstBracket, lastBracket + 1)
        }
        return cleaned.trim()
    }

    /**
     * Generates a ready-to-copy Arabic prompt for ChatGPT, Claude, or Gemini so the user can
     * plan an entire week or month and get back strict JSON matching Nabda's importer schema.
     */
    fun buildExternalAiPrompt(
        userGoalOrPlanHint: String = "",
        referenceDate: Date = Date()
    ): String {
        val today = ArabicCalendarUtils.startOfDay(referenceDate)
        val todayIso = ArabicCalendarUtils.formatIsoDate(today)
        val todayArabic = ArabicCalendarUtils.formatGregorianArabic(today)
        val nextDay1Iso = ArabicCalendarUtils.formatIsoDate(ArabicCalendarUtils.addDays(today, 1))
        val nextDay2Iso = ArabicCalendarUtils.formatIsoDate(ArabicCalendarUtils.addDays(today, 2))

        val customGoalSection = if (userGoalOrPlanHint.isNotBlank()) {
            "خطة وأهداف المستخدم المطلوب جدولتها:\n\"${userGoalOrPlanHint.trim()}\""
        } else {
            "أهدافي ومهامي التي أريد جدولتها خلال الأيام القادمة:\n[اكتب هنا موادك الدراسية، أو مشاريعك، أو خطتك الأسبوعية/الشهرية بالتفصيل]"
        }

        return """
أنت خبير تخطيط وإدارة وقت. أريد منك تنظيم خطتي وتوزيع المهام على الأيام بالتاريخ الميلادي بدقة لاستيرادها داخل تطبيق "نَبضة" (Nabda).

معلومات التاريخ المرجعية:
- تاريخ اليوم هو: $todayIso ($todayArabic).
- يبدأ الأسبوع في تطبيقي يوم السبت وينتهي يوم الجمعة.

$customGoalSection

التعليمات الصارمة للإخراج:
1. قسّم المهام بشكل متوازن وواقعي على التواريخ المناسبة بصيغة YYYY-MM-DD (مثلاً: $nextDay1Iso، $nextDay2Iso...).
2. حدد لكل مهمة أولوية (priority) بإحدى القيم الثلاث فقط باللغة الإنجليزية:
   - "HIGH" (للمهام الأساسية والضرورية جداً)
   - "MEDIUM" (للمهام المتوسطة والمراجعات)
   - "LOW" (للمهام الخفيفة أو التكميلية)
3. أخرج النتيجة بصيغة كود JSON صالح فقط بدون أي شرح إضافي قبله أو بعده، وبدون تغيير أسماء الحقول، مطابقاً تماماً لهذا الهيكل:

{
  "schedule": [
    {
      "date": "$nextDay1Iso",
      "tasks": [
        { "title": "مذاكرة محاضرة الباطنة الأولى", "priority": "HIGH" },
        { "title": "مراجعة السكشن", "priority": "MEDIUM" },
        { "title": "ترتيب المكتب", "priority": "LOW" }
      ]
    }
  ]
}
        """.trimIndent()
    }

    /**
     * Generates a ready-to-import sample JSON schedule starting from today/tomorrow.
     */
    fun buildSampleScheduleJson(referenceDate: Date = Date()): String {
        val today = ArabicCalendarUtils.startOfDay(referenceDate)
        val day1 = ArabicCalendarUtils.formatIsoDate(today)
        val day2 = ArabicCalendarUtils.formatIsoDate(ArabicCalendarUtils.addDays(today, 1))
        return """
{
  "schedule": [
    {
      "date": "$day1",
      "tasks": [
        { "title": "مذاكرة محاضرة الباطنة الأولى", "priority": "HIGH" },
        { "title": "مراجعة السكشن", "priority": "MEDIUM" },
        { "title": "ترتيب المكتب", "priority": "LOW" }
      ]
    },
    {
      "date": "$day2",
      "tasks": [
        { "title": "حل أسئلة المراجعة الأسبوعية", "priority": "HIGH" },
        { "title": "تلخيص النقاط المهمة", "priority": "MEDIUM" }
      ]
    }
  ]
}
        """.trimIndent()
    }
}
